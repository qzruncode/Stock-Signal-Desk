"""Judgment rubric text for each of the 8 criteria.

Each rubric is embedded in the LLM prompt as the "判定标准" section.
"""

MAINLINE_POSITION = """\
判断该股票所属行业当前是否属于市场主线或分支主线。

通过条件（满足任一）：
- 行业板块资金净流入排名前10
- 近30天有明确的国家/部委级别政策支持
- 行业成交额占全市场比例持续上升
- 机构调研/持仓集中度显著提升

不通过条件：
- 行业资金持续净流出
- 无任何政策提及或市场关注
- 板块热度过低，成交额占比下降

注意区分：核心主线（强通过）vs 分支主线（通过）vs 非主线（不通过）"""

PROSPERITY_CYCLE = """\
判断该行业是否处于上升周期（景气上行）。

通过条件（满足任一）：
- 行业景气度评分 ≥ 65（满分100）
- 近3个季度营收增速逐季加速或维持高位（≥15%）
- PMI相关细分指标处于扩张区间（>50）
- 产能利用率环比提升

不通过条件：
- 景气度评分 < 50
- 营收增速连续2个季度下滑
- 行业处于明显的下行周期

注意区分：上行期（强通过）vs 底部复苏（通过）vs 顶部/下行期（不通过）"""

GROWTH_SPACE = """\
判断该行业未来3年是否有明确的增长空间（增量市场 vs 存量博弈）。

通过条件（满足任一）：
- 行业CAGR预测 ≥ 15%
- 核心产品/服务渗透率 < 40%（仍有大量提升空间）
- 有明确的新增需求来源（新市场/新技术替代/政策创造的新需求）
- 市场规模预测显示持续扩大

不通过条件：
- 行业增速 < 5%（低增长/零和博弈）
- 渗透率已 > 70%（天花板逼近）
- 增长主要靠抢占竞争对手份额而非新增需求
- 市场空间主要依赖存量替换"""

COMPETITION_LANDSCAPE = """\
判断该行业是否属于价格战/内卷行业。

通过条件（行业竞争格局健康）：
- 行业平均毛利率稳定或提升
- CR5 ≥ 50%（集中度合理，头部有定价权）
- 头部企业之间差异化明显，非纯价格竞争
- 新进入者壁垒较高

不通过条件（内卷/价格战）：
- 行业平均毛利率连续2个季度下滑
- CR5 < 30%（过度分散，恶性竞争）
- 出现明显的降价/促销战信号
- 产品高度同质化，竞争主要靠价格"""

GROWTH_DRIVERS = """\
判断该行业是否有明确且可持续的增长驱动因素（政策/技术/需求至少一种）。

通过条件（至少一种驱动力明确）：
- 政策驱动：近6个月有国家级/部委级产业政策出台，且政策方向明确利好
- 技术驱动：有重大技术突破或迭代，推动行业效率提升或创造新需求
- 需求驱动：下游需求数据（订单/出货量/装机量）持续增长

不通过条件：
- 无任何明确驱动力，行业增长缺乏支撑
- 纯概念炒作（有题材但无实质政策/技术/需求落地）
- 驱动力已过高峰，正在衰减"""

CATALYST_EVENTS = """\
判断未来6-12个月是否有可预见的催化事件。

通过条件（至少一个具体催化）：
- 已知的行业展会/峰会/产品发布会在未来6个月内
- 重要政策窗口期（如两会/产业规划发布/补贴到期前的抢装）
- 公司业绩拐点预期（如下季度财报有望超预期）
- 技术迭代节点（如新一代产品量产/商用）

不通过条件：
- 未来6-12个月无任何可预见的催化事件
- 催化事件已完全被市场消化（利好出尽）
- 催化事件时间不确定且概率较低"""

VALUATION_LEVEL = """\
判断当前估值是否已经透支了未来增长预期。

通过条件（估值合理或未高估）：
- PE历史分位数 < 70%
- PEG < 1.5
- 估值低于或接近行业平均水平
- 股价透支信号为"未透支"或"低透支"

不通过条件（估值透支）：
- PE历史分位数 ≥ 85% 且 PEG > 2.0
- 估值显著高于行业平均（>1.5倍）
- 股价透支信号为"高度透支"
- 当前估值已反映乐观预期，无安全边际"""

FATAL_RISKS = """\
扫描是否存在尚未被市场充分定价的致命风险。

通过条件（无致命风险）：
- 无重大财务异常（商誉/应收账款/现金流无严重问题）
- 无重大监管风险或政策打压信号
- 大股东无大规模质押或减持计划
- 无技术路线被颠覆的风险

不通过条件（存在致命风险）：
- 财务造假迹象（如应收异常增长、现金流与利润严重背离）
- 重大监管变化（如行业面临禁令/严格限制）
- 大股东高比例质押（>50%）且持续减持
- 核心技术/产品面临颠覆性替代
- 重大诉讼/违规事件"""

