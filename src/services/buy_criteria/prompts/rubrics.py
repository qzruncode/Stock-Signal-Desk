"""Evidence-dimension rubrics retained for focused evaluator diagnostics.

Each rubric is self-contained: role + criteria + JSON output format.
build_user_prompt simply concatenates rubric + data_summary.
"""

# --- Shared template fragments ---
_ROLE_PREFIX = (
    "你是负责A股组合的资深买方研究员。当前独立核验分析维度【{name}】。"
    "只能基于下方可回查证据判断；必须同时检查支持证据、反证、时间与统计口径。\n\n"
)
_JSON_SUFFIX = """\
## 请返回 JSON

{
"passed": true/false,
"confidence": "high/medium/low",
"verdict": "2-4句话，明确写出支持证据、主要反证以及为什么最终通过或不通过",
"details": {
  "key_evidence": ["最多4条，引用下方事实与时间"],
  "counter_evidence": ["最多3条"],
  "monitoring_points": ["最多3条后续验证点"]
}
}
"""


def _rubric(name: str, body: str, *, json_suffix: str = _JSON_SUFFIX) -> str:
    """Assemble a self-contained rubric."""
    return _ROLE_PREFIX.format(name=name) + body.strip() + "\n\n" + json_suffix


