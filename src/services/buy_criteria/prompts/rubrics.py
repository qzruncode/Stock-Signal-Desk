"""Judgment rubrics for the eight model-evaluated gates in the nine-gate chain.

Each rubric is self-contained: role + criteria + JSON output format.
build_user_prompt simply concatenates rubric + data_summary.
"""

# --- Shared template fragments ---
_ROLE_PREFIX = "你是一个A股行业分析师。请基于以下数据，判断【{name}】是否满足条件。\n\n"
_JSON_SUFFIX = """\
## 请返回 JSON

{
"passed": true/false,
"verdict": "2-3句话的定性判断"
}
"""


def _rubric(name: str, body: str, *, json_suffix: str = _JSON_SUFFIX) -> str:
    """Assemble a self-contained rubric."""
    return _ROLE_PREFIX.format(name=name) + body.strip() + "\n\n" + json_suffix


MAINLINE_POSITION = _rubric("主线地位", """\
判断本轮产业方向当前是否属于市场主线或分支主线，以及公司主营是否真实处在该产业链位置。

## 核心条件

- 市场侧：最新主线报告、未压缩的当前概念/行业板块、资金与成交证据中，多项独立证据共同指向该细分方向正在成为当前主线或活跃分支
- 公司侧：公司正式主营、产品、经营范围或正式披露能证明其位于该产业链位置
- 产业链映射应按业务逻辑和产品作用判断，不能按公司名、行业名、产品名做字符串匹配

## 不通过条件

- 市场侧只有孤立的单日涨跌、单一资金流或情绪热度，缺少相互印证
- 仅有概念关联，没有主营业务实际受益逻辑
- 只有宽泛法定行业名称，未识别公司实际产品所处的细分产业链

## 注意

- "候选主线"不等于"当前主线"。
- 主线报告是高层摘要，不是细分方向的封闭白名单。某个细分分支未在摘要中逐字出现，不得据此直接否决；应继续核验未压缩板块数据、结构化产业方向成员关系和公司正式业务资料。
- 概念池混合了大量行业、风格和重复口径。不能因为某个分支的绝对涨幅序号不在最前，就直接推导其不是当前主线；应同时比较资金流排名、涨幅强度、上位产业主题是否共振，以及公司是否处于核心产业位置。半导体等另一条主线更强，也不自动排除人形机器人等并行主线。
- 结构化概念板块成员关系只证明候选映射，不单独证明公司有订单、收入或竞争优势；这些在下一项“产业竞争力与真实受益”继续严格核验。
- 请求方向、候选召回覆盖方向及板块别名都不能反推公司具体产品。verdict 描述公司产品时只能引用公司正式主营、经营范围或正式披露，严禁把候选召回方向改写成公司主营。
- 报告不可用时不得凭模型记忆补结论；只有当前市场板块证据、结构化映射和公司正式业务资料均可核验且相互印证，才可通过。
""")

INDUSTRIAL_COMPETITIVENESS = _rubric("产业竞争力与真实受益", """\
判断公司是否真正受益于当前投资逻辑，并具备可核验的产业竞争力。

## 核心条件（必须全部满足才通过）

1. 真实受益：主营产品、已披露业务或公司级事实与本轮产业逻辑直接相关，不能只有概念板块关系。
2. 真实经营证据：以下路径是并列的替代关系，满足任一条即可证明相关业务真实存在，不要求同时具备：
   - 财报已披露相关分业务收入、利润或主营构成；
   - 公司正式资料证明相关产品已经是持续经营的主营/成熟产品，而非概念储备；
   - 正式披露或可交叉核验的订单、销量、客户应用、产能/产量、量产、出货或连续增速。
3. 竞争力证据：至少有技术壁垒、客户壁垒、规模/成本优势、市场份额、认证资质、良率或盈利能力
   优势中的一项，且不能只使用公司自我宣传。

## 通过约束

- 至少一项业务真实性证据必须来自财报主营构成、公司正式资料、正式公告或其他公司正式披露。
- 研报和新闻可以补充订单、客户、销量、产能和行业地位，但不能单独把概念关联升级为真实受益。
- 相关业务未单独披露收入或利润并不自动判失败。对已经商业化的通用核心零部件，不要求公司必须披露带有某一下游主题名称的专项订单；可结合正式产品/主营资料、客户应用、连续经营表现和第三方产业地位综合判断。
- 客户名称因保密未披露、没有单独发布订单公告，也不等于“没有客户或没有订单”；只能如实标注证据边界，不能把未披露当成负面事实。

## 不通过条件（任一满足即不通过）

- 只有概念、技术储备、互动平台表态或模糊的“积极布局”。
- 找不到任何正式业务资料，且也没有可回查的经营或产业地位证据。
- 业务相关但缺少可验证的竞争优势，或竞争优势已明显恶化。
""")

PROSPERITY_CYCLE = _rubric("景气上行周期", """\
判断该公司真实受益的细分行业是否处于上升周期（景气上行）。

注意：如果"行业"字段过宽，需要结合主营业务和产品识别真实细分行业。

## 核心条件（必须全部满足才通过）

1. 财务趋势确认：最近 3-4 个季度营收同比呈现改善趋势，或维持高位增长。

   - 如果营收同比逐季加速，视为强通过信号。
   - 如果营收同比虽连续回落，但最新增速仍 ≥30%，且毛利率未连续下滑，不应直接判为下行，可视为"高景气延续 / 边际放缓"。
   - 如果营收同比连续 2 个季度下滑，且最新增速 <15%，或同时出现毛利率连续下滑，才视为财务趋势走弱。

2. 供需关系信号：行业需求端出现加速信号，且必须与公司真实细分行业直接相关，可从新闻/研报/政策中识别
   （如订单增长、扩产涨价、下游需求爆发、政策利好、产业链公司共振等）。

## 辅助证据（影响确信度，不单独决定通过/不通过）

- 板块排名和资金流 — 仅反映市场情绪，板块涨 ≠ 景气上行，资金流 ≠ 周期拐点
- 宏观 PMI — 仅反映宏观经济上下文，制造业 PMI >50 是整体扩张环境，不等于行业景气

## 无效证据

以下内容不得作为供需关系通过依据：

- 泛行业新闻
- 地区规上工业增加值
- 无关公司股价异动
- 无关公司风险公告
- 与公司主营业务弱相关的题材新闻
- 只有市场情绪，没有订单、价格、出货、资本开支、政策落地等产业证据

## 不通过条件（任一满足即不通过）

- 营收增速连续 2 个季度下滑，且最新营收同比 <15%
- 营收增速连续 2 个季度下滑，同时毛利率连续下滑
- 毛利率持续下滑（价格战/内卷信号）
- 供需信号与公司真实细分行业无关或证据不足
- 行业处于明确的产能过剩/需求萎缩周期

注意区分：上行期（强通过）vs 高景气延续/底部复苏（谨慎通过）vs 顶部/下行期（不通过）

## 判断约束

- 核心条件（财务趋势 + 供需信号）必须全部满足才判为通过。
- 板块排名和资金流仅反映市场情绪，不得单独作为景气上行的判定依据。
- 宏观 PMI 反映整体经济环境，制造业 PMI >50 不等于具体行业景气上行。
- 如果财务趋势与供需信号结论矛盾，需要在 verdict 里说明矛盾点。
- 如果财务仍强但供需证据不足，可判为谨慎通过或不通过，但必须说明证据缺口。
""")

GROWTH_SPACE = _rubric("成长空间", """\
判断该行业未来3年是否有明确的增长空间（增量市场 vs 存量博弈）。

## 通过条件

- 行业CAGR预测 ≥ 15%
- 核心产品/服务渗透率 < 40%（仍有大量提升空间）
- 有明确的新增需求来源（新市场/新技术替代/政策创造的新需求）
- 市场规模预测显示持续扩大

## 不通过条件

- 行业增速 < 5%（低增长/零和博弈）
- 渗透率已 > 70%（天花板逼近）
- 增长主要靠抢占竞争对手份额而非新增需求
- 市场空间主要依赖存量替换
""")

COMPETITION_LANDSCAPE = _rubric("竞争格局", """\
判断该行业是否属于价格战/内卷行业。

## 通过条件（行业竞争格局健康）

- 公司毛利率稳定或提升，且若有行业平均数据则不明显弱于行业
- 行业集中度合理，头部企业有定价权或份额优势
- 头部企业之间差异化明显，非纯价格竞争
- 新进入者壁垒较高

## 不通过条件（内卷/价格战）

- 行业平均毛利率连续下滑，或公司毛利率至少连续两个季度下滑且有同一细分行业的降价/过剩证据交叉验证
- 行业过度分散（板块中参与企业众多且头部优势不明显）
- 出现明显的降价/促销战信号（新闻中出现降价、价格战、内卷等关键词）
- 产品高度同质化，竞争主要靠价格

## 证据边界

- 只判断公司真实受益的细分产品行业。其他行业的价格战、产能过剩或利润压缩材料一律无效。
- 股价、板块涨跌、资金流和个股新闻中的涨跌都不是竞争格局证据，不得用来证明内卷。
- 单个季度毛利率回落不等于连续下滑；不得把公司单季毛利率变化改写为行业平均趋势。
- 通过需要份额、技术/客户壁垒、规模成本、差异化或盈利能力中的正面证据；不能仅凭“没找到价格战新闻”通过。
""")

