CATALYST_EVENTS = _rubric("催化事件", """\
判断未来6-12个月是否有可预见的催化事件。

## 事件分类

- `company_milestone`：公司正式披露且有明确窗口的投产、交付、量产、产品发布、客户定点或订单兑现。
- `financial_validation`：已预约的财报/业绩披露窗口，且正文或经营数据说明了需要验证的收入、利润、毛利率、现金流或业务放量预期。
- `sector_mapping`：行业大会、关键客户事件或政策窗口，只能作为板块映射，不得改写为公司已获订单。
- `conditional_watch`：有业务方向但客户、订单、销量、量产或时间尚未被正式披露，只列为观察条件，不单独支持通过。

## 通过条件（至少一个具体催化）

- 已知的行业展会/峰会/产品发布会在未来6个月内
- 重要政策窗口期（如两会/产业规划发布/补贴到期前的抢装）
- 公司业绩拐点预期（如下季度财报有望超预期）
- 技术迭代节点（如新一代产品量产/商用）
- 公司年报、半年报或正式项目公告明确写出的未来投产、交付、产能释放时间窗

## 不通过条件

- 未来6-12个月无任何可预见的催化事件
- 催化事件已完全被市场消化（利好出尽）
- 催化事件时间不确定且概率较低
- 数据源失败，或没有至少一个可回查来源和明确的未来时间窗口

## 证据与结论边界

- 必须阅读“正式定期报告正文中的未来时间窗”，不能只看最近公告标题。
- 定期报告预约日是核验窗口，不是天然利好；只有披露日期时不得单独判通过。
- 行业大会、关键客户财报和产业政策是板块映射催化；没有公司级证据时不得声称公司订单或收入确定兑现。
- 公司正式报告明确的交付/投产窗口可作为公司里程碑，但仍要说明后续需要验证的收入规模、产能利用率、客户复购或利润贡献。
- `passed=true` 至少需要一个 `company_milestone`，或一个有明确经营预期支撑的 `financial_validation`；只有 `sector_mapping`/`conditional_watch` 必须不通过。
""", json_suffix=_CATALYST_JSON_SUFFIX)

