"""Judgment rubric text for each of the 8 criteria.

Each rubric is self-contained: role + criteria + JSON output format.
build_user_prompt simply concatenates rubric + data_summary.
"""

# --- Shared template fragments ---
_ROLE_PREFIX = "你是一个A股行业分析师。请基于以下数据，判断【{name}】是否满足条件。\n\n"
_JSON_SUFFIX = """\
## 请返回 JSON

{
"passed": true/false,
"verdict": "2-3句话的定性判断"
}
"""


def _rubric(name: str, body: str) -> str:
    """Assemble a self-contained rubric."""
    return _ROLE_PREFIX.format(name=name) + body.strip() + "\n\n" + _JSON_SUFFIX


MAINLINE_POSITION = _rubric("主线地位", """\
判断该股票所属行业当前是否属于市场主线或分支主线。

## 核心条件

- 在最新市场主线报告中，行业或主营业务能明确映射到当前主线/分支主线
- 主线报告中的分支、证据或叙事，与公司主营/产品方向存在明确对应关系

## 不通过条件

- 未命中最新市场主线报告中的当前主线，只能算候选观察方向
- 只有行业资金流、板块涨跌幅或短线热度，缺少主线映射证据
- 仅有概念关联，没有主营业务实际受益逻辑

## 注意

- "候选主线"不等于"当前主线"
- 不要把行业板块的单日涨跌幅或资金流排名，当成股票本身的涨跌或主线成立依据
- 只有当前主线/分支主线映射成立，才能判为通过
""")

PROSPERITY_CYCLE = _rubric("景气上行周期", """\
判断该公司真实受益的细分行业是否处于上升周期（景气上行）。

注意：如果"行业"字段过宽，需要结合主营业务和产品识别真实细分行业。

## 核心条件（必须全部满足才通过）

1. 财务趋势确认：最近 3-4 个季度营收同比呈现改善趋势，或维持高位增长。

   - 如果营收同比逐季加速，视为强通过信号。
   - 如果营收同比虽连续回落，但最新增速仍 ≥30%，且毛利率未连续下滑，不应直接判为下行，可视为"高景气延续 / 边际放缓"。
   - 如果营收同比连续 2 个季度下滑，且最新增速 <15%，或同时出现毛利率连续下滑，才视为财务趋势走弱。

2. 供需关系信号：行业需求端出现加速信号，且必须与公司真实细分行业直接相关，可从新闻/研报/政策中识别
   （如订单增长、扩产涨价、下游需求爆发、政策利好、产业链公司共振等）。

## 辅助证据（影响确信度，不单独决定通过/不通过）

- 板块排名和资金流 — 仅反映市场情绪，板块涨 ≠ 景气上行，资金流 ≠ 周期拐点
- 宏观 PMI — 仅反映宏观经济上下文，制造业 PMI >50 是整体扩张环境，不等于行业景气

## 无效证据

以下内容不得作为供需关系通过依据：

- 泛行业新闻
- 地区规上工业增加值
- 无关公司股价异动
- 无关公司风险公告
- 与公司主营业务弱相关的题材新闻
- 只有市场情绪，没有订单、价格、出货、资本开支、政策落地等产业证据

## 不通过条件（任一满足即不通过）

- 营收增速连续 2 个季度下滑，且最新营收同比 <15%
- 营收增速连续 2 个季度下滑，同时毛利率连续下滑
- 毛利率持续下滑（价格战/内卷信号）
- 供需信号与公司真实细分行业无关或证据不足
- 行业处于明确的产能过剩/需求萎缩周期

注意区分：上行期（强通过）vs 高景气延续/底部复苏（谨慎通过）vs 顶部/下行期（不通过）

## 判断约束

- 核心条件（财务趋势 + 供需信号）必须全部满足才判为通过。
- 板块排名和资金流仅反映市场情绪，不得单独作为景气上行的判定依据。
- 宏观 PMI 反映整体经济环境，制造业 PMI >50 不等于具体行业景气上行。
- 如果财务趋势与供需信号结论矛盾，需要在 verdict 里说明矛盾点。
- 如果财务仍强但供需证据不足，可判为谨慎通过或不通过，但必须说明证据缺口。
""")

GROWTH_SPACE = _rubric("成长空间", """\
判断该行业未来3年是否有明确的增长空间（增量市场 vs 存量博弈）。

## 通过条件

- 行业CAGR预测 ≥ 15%
- 核心产品/服务渗透率 < 40%（仍有大量提升空间）
- 有明确的新增需求来源（新市场/新技术替代/政策创造的新需求）
- 市场规模预测显示持续扩大

## 不通过条件

- 行业增速 < 5%（低增长/零和博弈）
- 渗透率已 > 70%（天花板逼近）
- 增长主要靠抢占竞争对手份额而非新增需求
- 市场空间主要依赖存量替换
""")

COMPETITION_LANDSCAPE = _rubric("竞争格局", """\
判断该行业是否属于价格战/内卷行业。

## 通过条件（行业竞争格局健康）

- 行业平均毛利率稳定或提升（当前毛利率 ≥ 行业平均，且趋势不连续下滑）
- 行业集中度合理（板块排名靠前，头部企业有定价权）
- 头部企业之间差异化明显，非纯价格竞争
- 新进入者壁垒较高

## 不通过条件（内卷/价格战）

- 行业平均毛利率连续下滑
- 行业过度分散（板块中参与企业众多且头部优势不明显）
- 出现明显的降价/促销战信号（新闻中出现降价、价格战、内卷等关键词）
- 产品高度同质化，竞争主要靠价格
""")

GROWTH_DRIVERS = _rubric("增长驱动", """\
判断该行业是否有明确且可持续的增长驱动因素（政策/技术/需求至少一种）。

## 通过条件（至少一种驱动力明确）

- 政策驱动：近6个月有国家级/部委级产业政策出台，且政策方向明确利好
- 技术驱动：有重大技术突破或迭代，推动行业效率提升或创造新需求
- 需求驱动：下游需求数据（订单/出货量/装机量）持续增长

## 不通过条件

- 无任何明确驱动力，行业增长缺乏支撑
- 纯概念炒作（有题材但无实质政策/技术/需求落地）
- 驱动力已过高峰，正在衰减
""")

CATALYST_EVENTS = _rubric("催化事件", """\
判断未来6-12个月是否有可预见的催化事件。

## 通过条件（至少一个具体催化）

- 已知的行业展会/峰会/产品发布会在未来6个月内
- 重要政策窗口期（如两会/产业规划发布/补贴到期前的抢装）
- 公司业绩拐点预期（如下季度财报有望超预期）
- 技术迭代节点（如新一代产品量产/商用）

## 不通过条件

- 未来6-12个月无任何可预见的催化事件
- 催化事件已完全被市场消化（利好出尽）
- 催化事件时间不确定且概率较低
""")

VALUATION_LEVEL = _rubric("估值水平", """\
判断当前估值是否已经透支了未来增长预期。

## 通过条件（估值合理或未高估）

- PE历史分位数 < 70%
- PEG < 1.5
- 估值低于或接近行业平均水平
- 股价透支信号为"未透支"或"低透支"

## 不通过条件（估值透支）

- PE历史分位数 ≥ 85% 且 PEG > 2.0
- 估值显著高于行业平均（>1.5倍）
- 股价透支信号为"高度透支"
- 当前估值已反映乐观预期，无安全边际
""")

FATAL_RISKS = _rubric("致命风险", """\
扫描是否存在尚未被市场充分定价的致命风险。

## 通过条件（无致命风险）

- 无重大财务异常（商誉/应收账款/现金流无严重问题）
- 无重大监管风险或政策打压信号
- 大股东无大规模质押或减持计划
- 无技术路线被颠覆的风险

## 不通过条件（存在致命风险）

- 财务造假迹象（如应收异常增长、现金流与利润严重背离）
- 重大监管变化（如行业面临禁令/严格限制）
- 大股东高比例质押（>50%）且持续减持
- 核心技术/产品面临颠覆性替代
- 重大诉讼/违规事件
""")

